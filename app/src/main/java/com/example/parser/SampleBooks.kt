首先，在内心焦虑的前提下思考问题，就会疏忽如何将盘子洗净或如何在最短时间里完成任务。这是第一个“无意义”。其次，如果希望孩子吃得干净些，即使生气也不会有任何效果。这是第二个“无意义”。与此相比，应该有一颗平常心，这样对大家说：“我为你们做饭，如果你们不能吃干净，我会感到很伤心，我会很讨厌洗盘子。我不想让自己的心情变糟，我们共居一室，如果你们看见我的心情不好，你们也会感到压抑。所以，希望你们能认真吃饭。”
思考问题时，要避免不必要的能量消耗。此时，只要适当地考虑最低限度的事情，考虑如何排除无用之妄念和让自己空忙一通的思考，进而做到克服烦恼，这些才是修行的起点，同时也是修行的终点。

